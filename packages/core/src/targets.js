import { strToU8, strFromU8, packZip } from './bundle.js';

/** Files written into every generated `www` directory. */
export function buildWwwTree(bundle, bridgeJs) {
  const files = new Map();
  for (const [name, data] of bundle.files) {
    // Never let input shadow our runtime files.
    if (name.startsWith('__easyapp_')) continue;
    files.set(name, data);
  }
  files.set('__easyapp_bridge.js', strToU8(bridgeJs));
  files.set('__easyapp_manifest.json', strToU8(JSON.stringify(bundle.manifest, null, 2)));
  return files;
}

/**
 * Rewrite absolute asset URLs to relative ones. A leading "/" resolves against
 * the host root, which does not exist inside a compiled bundle.
 */
export function normalizeHtmlPaths(html) {
  let out = html;
  const warnings = [];

  // src="/x" href="/x" (but leave protocol-relative "//" and full URLs alone)
  out = out.replace(/(\s(?:src|href)\s*=\s*)(["'])\/(?!\/)([^"']*)\2/gi,
    (match, prefix, quote, path) => {
      warnings.push(`Rewrote absolute asset path "/${path}" to "./${path}"`);
      return `${prefix}${quote}./${path}${quote}`;
    });

  // CSS url(/x)
  out = out.replace(/url\(\s*(["']?)\/(?!\/)([^)]*?)\1\s*\)/gi,
    (match, quote, path) => {
      warnings.push(`Rewrote absolute CSS url "/${path}"`);
      return `url(${quote}./${path}${quote})`;
    });

  return { html: out, warnings };
}

/** Apply path normalisation to every HTML/CSS file in the tree. */
export function normalizeTree(files) {
  const warnings = [];
  const out = new Map();
  for (const [name, data] of files) {
    if (/\.(html?|css)$/i.test(name)) {
      const text = strFromU8(data);
      const res = normalizeHtmlPaths(text);
      out.set(name, strToU8(res.html));
      for (const w of res.warnings) warnings.push(`${name}: ${w}`);
    } else {
      out.set(name, data);
    }
  }
  return { files: out, warnings };
}

/** Detect patterns that cannot work inside a compiled, offline bundle. */
export function lintBundle(bundle) {
  const issues = [];
  const permissions = bundle.manifest.permissions;

  for (const [name, data] of bundle.files) {
    if (!/\.(html?|js|mjs|css)$/i.test(name)) continue;
    const text = strFromU8(data);

    // External resources break offline mode.
    const cdn = text.match(/(?:src|href)\s*=\s*["']https?:\/\/[^"']+["']/gi) || [];
    for (const hit of cdn.slice(0, 5)) {
      issues.push({
        level: permissions.includes('internet') ? 'warning' : 'error',
        file: name,
        message: `External resource will not load offline: ${hit.trim().slice(0, 120)}`,
      });
    }

    if (/\bfetch\s*\(|XMLHttpRequest|new\s+WebSocket/.test(text) && !permissions.includes('internet')) {
      issues.push({
        level: 'warning',
        file: name,
        message: 'Network API used but the "internet" permission is not enabled. '
          + 'Add <!-- easyapp:permission internet --> or enable the checkbox.',
      });
    }

    if (/easyapp\s*\.\s*files\s*\./.test(text) && !permissions.includes('files')) {
      issues.push({
        level: 'warning',
        file: name,
        message: 'easyapp.files is used but the "files" permission is not enabled.',
      });
    }

    if (/\blocalStorage\b/.test(text)) {
      issues.push({
        level: 'info',
        file: name,
        message: 'localStorage may be cleared by the OS. Prefer easyapp.storage for durable data.',
      });
    }
  }

  if (!bundle.files.has(bundle.entry)) {
    issues.push({ level: 'error', file: bundle.entry, message: 'Entry file is missing' });
  }
  return issues;
}

/** Payload consumed by the native desktop hosts and the Windows installer. */
export function buildDesktopPayload(bundle, bridgeJs, { hostBinary = null, hostName = 'app.exe' } = {}) {
  const normalized = normalizeTree(buildWwwTree(bundle, bridgeJs));
  const files = new Map();
  for (const [name, data] of normalized.files) files.set(`www/${name}`, data);
  if (hostBinary) files.set(hostName, hostBinary);
  return { files, warnings: normalized.warnings, zip: packZip(files) };
}

/**
 * Materialise an Android Gradle project from the template.
 * The template lives in `templates/runtime-android` and is copied verbatim,
 * then the web assets and gradle.properties are injected.
 */
export function buildAndroidProject(bundle, bridgeJs, templateFiles) {
  const normalized = normalizeTree(buildWwwTree(bundle, bridgeJs));
  const files = new Map(templateFiles);

  for (const [name, data] of normalized.files) {
    files.set(`app/src/main/assets/www/${name}`, data);
  }

  const m = bundle.manifest;
  const props = [
    '# Generated by EasyAnyHtmlUIProgramm. Do not edit by hand.',
    'org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8',
    'android.useAndroidX=false',
    'android.nonTransitiveRClass=true',
    `appId=${m.id}`,
    `appName=${escapePropertyValue(m.name)}`,
    `appVersion=${m.version}`,
    `appVersionCode=${m.versionCode}`,
    `allowInternet=${m.permissions.includes('internet')}`,
    `allowFiles=${m.permissions.includes('files')}`,
    `orientation=${m.orientation}`,
    '',
  ].join('\n');
  files.set('gradle.properties', strToU8(props));

  return { files, warnings: normalized.warnings };
}

function escapePropertyValue(value) {
  // Java properties: escape backslashes, colons and newlines.
  return String(value).replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/:/g, '\\:');
}

/** A .desktop entry plus launcher script for the Linux package. */
export function buildLinuxExtras(bundle) {
  const m = bundle.manifest;
  const desktop = [
    '[Desktop Entry]',
    'Type=Application',
    `Name=${m.name}`,
    `Comment=${m.description || m.name}`,
    'Exec=easyapp-run',
    'Icon=easyapp',
    'Terminal=false',
    'Categories=Utility;',
    `StartupWMClass=${m.id}`,
    '',
  ].join('\n');

  const launcher = [
    '#!/bin/sh',
    '# SPDX-License-Identifier: GPL-3.0-or-later',
    'set -e',
    'HERE="/opt/easyapp"',
    'exec "$HERE/app" "$@"',
    '',
  ].join('\n');

  return { desktop, launcher };
}

