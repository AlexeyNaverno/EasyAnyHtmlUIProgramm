/**
 * Prepare templates/runtime-android for a direct Gradle build of the compiler
 * app itself (used by F-Droid, which runs Gradle on its own).
 *
 * It generates the UI assets, copies them into the Gradle project and writes
 * gradle.properties with the compiler's identity and permissions.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, cpSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

import { loadBundle } from '../packages/core/src/bundle.js';
import { buildWwwTree } from '../packages/core/src/targets.js';
import { zipSync } from 'fflate';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const UI_BUILD = join(ROOT, 'build/ui');
const PROJECT = join(ROOT, 'templates/runtime-android');
const ASSETS = join(PROJECT, 'app/src/main/assets/www');

function walk(dir, prefix = '') {
  const out = new Map();
  for (const entry of readdirSync(dir)) {
    if (['build', '.gradle', 'node_modules'].includes(entry)) continue;
    const full = join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(full).isDirectory()) {
      for (const [k, v] of walk(full, rel)) out.set(k, v);
    } else {
      out.set(rel, new Uint8Array(readFileSync(full)));
    }
  }
  return out;
}

// 1. Generate the standalone UI assets.
/*
 * Embed whatever generic runtimes this environment can build. F-Droid provides
 * a JDK and the Android SDK but not Zig or WebKitGTK headers, so the F-Droid
 * variant may support fewer native targets than the GitHub release. That is
 * reported rather than hidden; nothing is downloaded or committed as a blob.
 */
try {
  const { spawnSync } = await import('node:child_process');
  const res = spawnSync(process.execPath,
    [join(ROOT, 'scripts', 'build-runtimes.mjs')],
    { stdio: 'inherit' });
  if (res.status !== 0) console.log('Some runtimes were unavailable; continuing.');
} catch (err) {
  console.log(`Runtime generation skipped: ${err.message}`);
}

execFileSync(process.execPath, [join(ROOT, 'scripts/build-ui.mjs'), '--assets-only'], {
  stdio: 'inherit',
});

// 2. Parse the generated entry so the manifest comes from the same directives
//    the rest of the pipeline uses.
const uiFiles = walk(UI_BUILD);
const zip = zipSync(Object.fromEntries(uiFiles), { level: 6 });
const bundle = loadBundle(zip, { filename: 'compiler-ui.zip' });
const bridge = readFileSync(join(ROOT, 'packages/core/runtime/bridge.js'), 'utf8');
const www = buildWwwTree(bundle, bridge);

// 3. Write the assets into the Gradle project.
mkdirSync(ASSETS, { recursive: true });
for (const [name, data] of www) {
  const full = join(ASSETS, name);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, data);
}

// 4. Write gradle.properties with the compiler's identity.
const m = bundle.manifest;
const escapeProp = (v) => String(v).replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/:/g, '\\:');
const props = [
  '# Generated by scripts/prepare-fdroid.mjs — do not edit by hand.',
  'org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8',
  'android.useAndroidX=false',
  'android.nonTransitiveRClass=true',
  `appId=${m.id}`,
  `appName=${escapeProp(m.name)}`,
  `appVersion=${m.version}`,
  `appVersionCode=${m.versionCode}`,
  `allowInternet=${m.permissions.includes('internet')}`,
  `allowFiles=${m.permissions.includes('files')}`,
  `orientation=${m.orientation}`,
  '',
].join('\n');
writeFileSync(join(PROJECT, 'gradle.properties'), props);

console.log(`Prepared ${PROJECT}`);
console.log(`  appId=${m.id} name=${m.name} permissions=${m.permissions.join(',') || '(none)'}`);
console.log(`  assets: ${www.size} files`);
